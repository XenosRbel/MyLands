-- 0007_clans_alliances_castles (ML-B05): clans, clan roles, member unions (alliances), clan pacts, castles and standards.
-- Append-only. The released tables alliances, alliance_relations and players.alliance_* stay and keep working.
-- Naming: the released table "alliances" holds a CLAN (a group of players). The new table player_alliances holds an
-- ALLIANCE in the rule sense (S-01: up to 7 players, support and joint attack). See DB_DESIGN.md section 7.
-- Limits 7, 3 and 6 are fixed by the source rules. Values marked UNKNOWN in the source (clan capacity by level) are not invented:
-- clans.capacity is NULL (no database limit) until the server writes the pack value.

-- Composite-FK targets so child rows carry the same world as the parent.
ALTER TABLE players ADD CONSTRAINT players_id_world_uniq UNIQUE (id, world_id);

-- ---------------------------------------------------------------------------
-- 1. Clan roles (reference table) and clans
-- ---------------------------------------------------------------------------
CREATE TABLE clan_roles (
    id         TEXT PRIMARY KEY CHECK (id ~ '^[a-z][a-z0-9_]{0,31}$'),
    rank       INT NOT NULL UNIQUE CHECK (rank >= 1),  -- 1 = highest
    singleton  BOOLEAN NOT NULL DEFAULT false           -- at most one member per clan holds the role
);
COMMENT ON TABLE clan_roles IS 'Reference: clan member roles. singleton roles are held by one member per clan (checked at commit).';
INSERT INTO clan_roles(id, rank, singleton) VALUES
    ('leader', 1, true), ('officer', 2, false), ('treasurer', 3, true), ('war_minister', 4, true), ('member', 9, false);

CREATE TABLE clans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_id     BIGINT NOT NULL REFERENCES worlds(id) ON DELETE RESTRICT,
    name         TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64),
    tag          TEXT NOT NULL CHECK (length(tag) BETWEEN 1 AND 16),
    description  TEXT NOT NULL DEFAULT '',
    level        INT NOT NULL DEFAULT 1 CHECK (level >= 1),  -- upper bound comes from the pack
    capacity     INT CHECK (capacity >= 1),                  -- NULL = pack value not written yet (UNKNOWN), no database limit
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    disbanded_at TIMESTAMPTZ,
    UNIQUE (id, world_id)
);
CREATE UNIQUE INDEX clans_name ON clans(world_id, lower(name)) WHERE disbanded_at IS NULL;
CREATE UNIQUE INDEX clans_tag  ON clans(world_id, lower(tag))  WHERE disbanded_at IS NULL;
COMMENT ON TABLE clans IS 'Clan. Mirrors the released table alliances (same ids) via trigger alliances_sync_clan until the Go cutover.';
COMMENT ON TABLE alliances IS 'DEPRECATED (0007): a clan. Use clans. Still written by released code; remove after the Go cutover.';

CREATE TABLE clan_members (
    player_id  BIGINT PRIMARY KEY,  -- a player is in at most one clan
    clan_id    BIGINT NOT NULL,
    world_id   BIGINT NOT NULL,
    role_id    TEXT NOT NULL DEFAULT 'member' REFERENCES clan_roles(id) ON DELETE RESTRICT,
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (clan_id, world_id)   REFERENCES clans(id, world_id)   ON DELETE CASCADE,
    FOREIGN KEY (player_id, world_id) REFERENCES players(id, world_id) ON DELETE CASCADE
);
CREATE INDEX clan_members_clan ON clan_members(clan_id, role_id);
COMMENT ON TABLE clan_members IS 'Clan membership: one row per player with one role. Mirrors players.alliance_id/alliance_role (DEPRECATED) via trigger players_sync_clan_member.';

-- Capacity: serialised by the clan row lock.
CREATE FUNCTION clan_members_capacity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE cap INT; n BIGINT;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.clan_id = OLD.clan_id THEN RETURN NEW; END IF;
    SELECT capacity INTO cap FROM clans WHERE id = NEW.clan_id FOR UPDATE;
    IF cap IS NOT NULL THEN
        SELECT count(*) INTO n FROM clan_members WHERE clan_id = NEW.clan_id;
        IF n >= cap THEN
            RAISE EXCEPTION 'clan % is full (capacity %)', NEW.clan_id, cap USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER clan_members_capacity BEFORE INSERT OR UPDATE OF clan_id ON clan_members
    FOR EACH ROW EXECUTE FUNCTION clan_members_capacity();

CREATE FUNCTION clans_capacity_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.capacity IS NOT NULL AND (SELECT count(*) FROM clan_members WHERE clan_id = NEW.id) > NEW.capacity THEN
        RAISE EXCEPTION 'clan % has more members than capacity %', NEW.id, NEW.capacity USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER clans_capacity_guard BEFORE UPDATE OF capacity ON clans
    FOR EACH ROW EXECUTE FUNCTION clans_capacity_guard();

-- Singleton roles are checked at commit so a leader hand-over inside one transaction can pass through two leaders.
CREATE FUNCTION clan_members_singleton_role() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM clan_roles WHERE id = NEW.role_id AND singleton) THEN
        PERFORM 1 FROM clans WHERE id = NEW.clan_id FOR UPDATE;
        IF (SELECT count(*) FROM clan_members WHERE clan_id = NEW.clan_id AND role_id = NEW.role_id) > 1 THEN
            RAISE EXCEPTION 'clan % has more than one %', NEW.clan_id, NEW.role_id USING ERRCODE = 'unique_violation';
        END IF;
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER clan_members_singleton_role AFTER INSERT OR UPDATE OF role_id, clan_id ON clan_members
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION clan_members_singleton_role();

-- Backfill and keep in step with the released tables.
INSERT INTO clans(id, world_id, name, tag, description, created_at, disbanded_at)
