SELECT id, alliance_id, world_id, COALESCE(alliance_role, 'member') FROM players WHERE alliance_id IS NOT NULL;

CREATE FUNCTION alliances_sync_clan() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO clans(id, world_id, name, tag, description, created_at, disbanded_at)
    VALUES (NEW.id, NEW.world_id, NEW.name, NEW.tag, NEW.description, NEW.created_at, NEW.disbanded_at)
    ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, tag = EXCLUDED.tag,
        description = EXCLUDED.description, disbanded_at = EXCLUDED.disbanded_at;
    RETURN NULL;
END $$;
CREATE TRIGGER alliances_sync_clan AFTER INSERT OR UPDATE ON alliances
    FOR EACH ROW EXECUTE FUNCTION alliances_sync_clan();

CREATE FUNCTION players_sync_clan_member() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.alliance_id IS NULL THEN
        DELETE FROM clan_members WHERE player_id = NEW.id;
    ELSE
        INSERT INTO clan_members(player_id, clan_id, world_id, role_id)
        VALUES (NEW.id, NEW.alliance_id, NEW.world_id, COALESCE(NEW.alliance_role, 'member'))
        ON CONFLICT (player_id) DO UPDATE SET
            joined_at = CASE WHEN clan_members.clan_id <> EXCLUDED.clan_id THEN now() ELSE clan_members.joined_at END,
            clan_id = EXCLUDED.clan_id, role_id = EXCLUDED.role_id;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER players_sync_clan_member AFTER INSERT OR UPDATE OF alliance_id, alliance_role ON players
    FOR EACH ROW EXECUTE FUNCTION players_sync_clan_member();
COMMENT ON COLUMN players.alliance_id IS 'DEPRECATED (0007): use clan_members.';
COMMENT ON COLUMN players.alliance_role IS 'DEPRECATED (0007): use clan_members.role_id.';

-- ---------------------------------------------------------------------------
-- 2. Alliance (S-01): a union of players, at most 7 members, dissolved through the 24 h state "breaking"
-- ---------------------------------------------------------------------------
CREATE TABLE player_alliances (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    world_id            BIGINT NOT NULL REFERENCES worlds(id) ON DELETE RESTRICT,
    status              TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','breaking','dissolved')),
    breaking_started_at TIMESTAMPTZ,
    break_deadline      TIMESTAMPTZ,
    dissolved_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, world_id),
    CHECK ((status = 'active') = (breaking_started_at IS NULL)),
    CHECK ((breaking_started_at IS NULL) = (break_deadline IS NULL)),
    CHECK (break_deadline IS NULL OR break_deadline = breaking_started_at + interval '24 hours'),
    CHECK ((status = 'dissolved') = (dissolved_at IS NOT NULL)),
    CHECK (dissolved_at IS NULL OR dissolved_at >= break_deadline)
);
CREATE INDEX player_alliances_breaking ON player_alliances(break_deadline) WHERE status = 'breaking';
COMMENT ON TABLE player_alliances IS 'Alliance of players (S-01). breaking lasts exactly 24 hours (break_deadline) and cannot be cancelled. Dissolved only after the deadline.';

CREATE FUNCTION player_alliances_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'dissolved' THEN
        RAISE EXCEPTION 'a dissolved alliance is final' USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status <> 'active' AND NEW.status = 'active' THEN
        RAISE EXCEPTION 'breaking an alliance cannot be cancelled' USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status = 'active' AND NEW.status = 'dissolved' THEN
        RAISE EXCEPTION 'an alliance must pass through breaking' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER player_alliances_transition BEFORE UPDATE OF status ON player_alliances
    FOR EACH ROW EXECUTE FUNCTION player_alliances_transition();

CREATE TABLE player_alliance_members (
    alliance_id  BIGINT NOT NULL,
    player_id    BIGINT NOT NULL,
    world_id     BIGINT NOT NULL,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (alliance_id, player_id),
    FOREIGN KEY (alliance_id, world_id) REFERENCES player_alliances(id, world_id) ON DELETE CASCADE,
    FOREIGN KEY (player_id, world_id)   REFERENCES players(id, world_id)          ON DELETE CASCADE
);
CREATE INDEX player_alliance_members_player ON player_alliance_members(player_id);
COMMENT ON TABLE player_alliance_members IS 'Alliance members, at most 7 per alliance (trigger). Whether a player may sit in several alliances is UNKNOWN, so it is not restricted.';

CREATE FUNCTION player_alliance_members_limit() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE st TEXT;
BEGIN
    SELECT status INTO st FROM player_alliances WHERE id = NEW.alliance_id FOR UPDATE;
    IF st <> 'active' THEN
        RAISE EXCEPTION 'alliance % is %, no new members', NEW.alliance_id, st USING ERRCODE = 'check_violation';
    END IF;
    IF (SELECT count(*) FROM player_alliance_members WHERE alliance_id = NEW.alliance_id) >= 7 THEN
        RAISE EXCEPTION 'alliance % already has 7 members', NEW.alliance_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER player_alliance_members_limit BEFORE INSERT ON player_alliance_members
    FOR EACH ROW EXECUTE FUNCTION player_alliance_members_limit();

-- ---------------------------------------------------------------------------
-- 3. Peace treaties and war declarations between clans: at most 3 active of each kind per clan
-- ---------------------------------------------------------------------------
CREATE TABLE clan_pacts (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    world_id       BIGINT NOT NULL,
    kind           TEXT NOT NULL CHECK (kind IN ('peace','war')),
    clan_id        BIGINT NOT NULL,  -- proposer or declarer
    other_clan_id  BIGINT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at       TIMESTAMPTZ,
    FOREIGN KEY (clan_id, world_id)       REFERENCES clans(id, world_id) ON DELETE CASCADE,
    FOREIGN KEY (other_clan_id, world_id) REFERENCES clans(id, world_id) ON DELETE CASCADE,
    CHECK (clan_id <> other_clan_id),
    CHECK (ended_at IS NULL OR ended_at >= created_at)
);
-- One active pact per pair of clans, whatever the kind.
CREATE UNIQUE INDEX clan_pacts_active_pair ON clan_pacts(LEAST(clan_id, other_clan_id), GREATEST(clan_id, other_clan_id)) WHERE ended_at IS NULL;
CREATE INDEX clan_pacts_clan  ON clan_pacts(clan_id, kind)       WHERE ended_at IS NULL;
CREATE INDEX clan_pacts_other ON clan_pacts(other_clan_id, kind) WHERE ended_at IS NULL;
COMMENT ON TABLE clan_pacts IS 'Peace treaty or war declaration between two clans. A clan holds at most 3 active pacts of each kind (trigger, either side).';

CREATE FUNCTION clan_pacts_limit() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c BIGINT;
BEGIN
    IF NEW.ended_at IS NOT NULL THEN RETURN NEW; END IF;
    -- Lock both clans in id order, so concurrent inserts serialise without deadlock.
    PERFORM 1 FROM clans WHERE id IN (NEW.clan_id, NEW.other_clan_id) ORDER BY id FOR UPDATE;
    FOREACH c IN ARRAY ARRAY[NEW.clan_id, NEW.other_clan_id] LOOP
        IF (SELECT count(*) FROM clan_pacts WHERE kind = NEW.kind AND ended_at IS NULL
                AND (clan_id = c OR other_clan_id = c) AND id IS DISTINCT FROM NEW.id) >= 3 THEN
            RAISE EXCEPTION 'clan % already has 3 active % pacts', c, NEW.kind USING ERRCODE = 'check_violation';
        END IF;
    END LOOP;
    RETURN NEW;
END $$;
CREATE TRIGGER clan_pacts_limit BEFORE INSERT OR UPDATE OF ended_at, kind, clan_id, other_clan_id ON clan_pacts
    FOR EACH ROW EXECUTE FUNCTION clan_pacts_limit();

-- Snapshot of released alliance_relations: nap -> peace, war -> war, one pact per pair. 'ally' has no clan pact.
-- Rows over the limit of 3 are skipped with a notice (the trigger rejects them).
DO $$
DECLARE rec RECORD;
BEGIN
    FOR rec IN
        SELECT DISTINCT ON (LEAST(rel.alliance_id, rel.other_id), GREATEST(rel.alliance_id, rel.other_id))
               a.world_id, rel.alliance_id, rel.other_id, rel.status, rel.updated_at
        FROM alliance_relations rel
        JOIN alliances a ON a.id = rel.alliance_id
        JOIN alliances b ON b.id = rel.other_id AND b.world_id = a.world_id
        WHERE rel.status IN ('nap','war') AND a.disbanded_at IS NULL AND b.disbanded_at IS NULL
        ORDER BY LEAST(rel.alliance_id, rel.other_id), GREATEST(rel.alliance_id, rel.other_id), rel.updated_at DESC
    LOOP
        BEGIN
            INSERT INTO clan_pacts(world_id, kind, clan_id, other_clan_id, created_at)
            VALUES (rec.world_id, CASE rec.status WHEN 'nap' THEN 'peace' ELSE 'war' END, rec.alliance_id, rec.other_id, rec.updated_at);
        EXCEPTION WHEN check_violation THEN
            RAISE NOTICE 'clan pact % -> % skipped: limit of 3', rec.alliance_id, rec.other_id;
        END;
    END LOOP;
END $$;
COMMENT ON TABLE alliance_relations IS 'DEPRECATED (0007): use clan_pacts. clan_pacts was filled once from this table and is not synced.';

-- ---------------------------------------------------------------------------
-- 4. Clan castles (at most 6 per clan) and standards bought per castle
-- ---------------------------------------------------------------------------
CREATE TABLE clan_castles (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    world_id     BIGINT NOT NULL REFERENCES worlds(id) ON DELETE RESTRICT,
    castle_key   TEXT NOT NULL CHECK (castle_key ~ '^[a-z0-9][a-z0-9_.:-]{0,63}$'),  -- map or pack id of the castle site
    clan_id      BIGINT,  -- NULL = held by castle monsters
    captured_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (world_id, castle_key),
    FOREIGN KEY (clan_id, world_id) REFERENCES clans(id, world_id) ON DELETE RESTRICT,
    CHECK ((clan_id IS NULL) = (captured_at IS NULL))
);
CREATE INDEX clan_castles_clan ON clan_castles(clan_id) WHERE clan_id IS NOT NULL;
COMMENT ON TABLE clan_castles IS 'Castle site and its owner clan. A clan owns at most 6 castles (trigger). Owner is released before a clan row is deleted (RESTRICT).';

CREATE FUNCTION clan_castles_limit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.clan_id IS NULL OR (TG_OP = 'UPDATE' AND NEW.clan_id IS NOT DISTINCT FROM OLD.clan_id) THEN RETURN NEW; END IF;
    PERFORM 1 FROM clans WHERE id = NEW.clan_id FOR UPDATE;
    IF (SELECT count(*) FROM clan_castles WHERE clan_id = NEW.clan_id) >= 6 THEN
        RAISE EXCEPTION 'clan % already owns 6 castles', NEW.clan_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER clan_castles_limit BEFORE INSERT OR UPDATE OF clan_id ON clan_castles
    FOR EACH ROW EXECUTE FUNCTION clan_castles_limit();

CREATE TABLE castle_standards (
    castle_id   BIGINT NOT NULL REFERENCES clan_castles(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL CHECK (kind IN ('peace','war')),
    quantity    INT NOT NULL DEFAULT 0 CHECK (quantity >= 0),  -- the upper bound comes from the pack
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (castle_id, kind)
);
COMMENT ON TABLE castle_standards IS 'Standards bought for one castle, per kind. Price and maximum stay in the Game Pack.';
